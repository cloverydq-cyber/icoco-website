// Keep the approved website stylesheet isolated from the authenticated app.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import postcss from 'postcss'

const directory = fileURLToPath(new URL('../src/styles/', import.meta.url))
const boundary = '.icoco-marketing'
for (const filename of ['website.css', 'site-additions.css']) {
  const source = fs.readFileSync(path.join(directory, 'source', filename), 'utf8')
    .replaceAll('Montserrat', 'IcocoMarketingMontserrat')
  const root = postcss.parse(source)
  const animations = new Map()
  root.walkAtRules('keyframes', rule => {
    animations.set(rule.params, `marketing-${rule.params}`)
    rule.params = `marketing-${rule.params}`
  })
  root.walkDecls(/^(animation|animation-name)$/, declaration => {
    for (const [before, after] of animations) {
      declaration.value = declaration.value.replace(new RegExp(`\\b${before}\\b`, 'g'), after)
    }
  })
  root.walkRules(rule => {
    let parent = rule.parent
    while (parent) {
      if (parent.type === 'atrule' && parent.name.endsWith('keyframes')) return
      parent = parent.parent
    }
    rule.selectors = rule.selectors.map(selector => {
      const scoped = selector.trim()
        .replace(/^(?::root|html|body|#app)(?=$|[\s.#:\[>+~])/, boundary)
        .replace(/^\.no-webgl\s/, `${boundary}.no-webgl `)
      return scoped.startsWith(boundary) ? scoped : `${boundary} ${scoped}`
    })
    // Preserve the original reduced-motion priority without !important rules.
    if (rule.nodes?.some(node => node.type === 'decl' && node.important)) {
      rule.selectors = rule.selectors.map(selector => `#marketing-root${selector}`)
      rule.walkDecls(declaration => { declaration.important = false })
    }
  })
  fs.writeFileSync(path.join(directory, filename), `/* Generated by scripts/scope-marketing-css.mjs. Edit styles/source instead. */\n${root.toString()}`)
}
